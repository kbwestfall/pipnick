"""
Sphinx configuration for the pipnick documentation.

Docstrings are NumPy style and rendered by ``numpydoc``, not by
``sphinx.ext.napoleon``.  ``numpydoc`` is the renderer numpy, scipy and astropy
use, and it can validate docstrings as well as render them.

Build with ``make html`` from this directory; see the Makefile.  The API pages
are generated by ``make apirst`` and must be regenerated and committed when the
package modules change.
"""

from importlib import metadata
from pathlib import Path
import tomllib


# -- Project information -----------------------------------------------------

def get_package_version():
    """
    Return the installed version of the package named in ``pyproject.toml``.

    Returns
    -------
    str
        The version.
    """
    project_file = Path(__file__).resolve().parents[1] / 'pyproject.toml'
    with open(project_file, 'rb') as f:
        return metadata.version(tomllib.load(f)['project']['name'])


project = 'pipnick'
author = 'Allison K. Eto & Kyle B. Westfall'
copyright = '2024-2026, Allison K. Eto & Kyle B. Westfall'
version = get_package_version()
release = version


# -- General configuration ---------------------------------------------------

extensions = [
    'sphinx.ext.autodoc',
    'numpydoc',
    'sphinx.ext.intersphinx',
    'sphinx.ext.mathjax',
    'sphinx.ext.todo',
    'sphinx.ext.viewcode',
    'sphinx_design',
]

root_doc = 'index'
source_suffix = '.rst'
# The release notes are included into whatsnew.rst, as in PypeIt, rather than
# built as pages of their own.
exclude_patterns = ['_build', 'releases/*.rst', 'figures', 'sphinx_warnings.out']
templates_path = []

pygments_style = 'sphinx'
todo_include_todos = True


# -- numpydoc ------------------------------------------------------------------

# The API pages written by sphinx-apidoc already document every member with
# autodoc; numpydoc listing them again would duplicate each one.
numpydoc_show_class_members = False
numpydoc_class_members_toctree = False


# -- autodoc -------------------------------------------------------------------

autodoc_member_order = 'bysource'


# -- intersphinx ---------------------------------------------------------------

intersphinx_mapping = {
    'python': ('https://docs.python.org/3', None),
    'numpy': ('https://numpy.org/doc/stable/', None),
    'scipy': ('https://docs.scipy.org/doc/scipy/', None),
    'astropy': ('https://docs.astropy.org/en/stable/', None),
    'matplotlib': ('https://matplotlib.org/stable/', None),
    'photutils': ('https://photutils.readthedocs.io/en/stable/', None),
    'ccdproc': ('https://ccdproc.readthedocs.io/en/stable/', None),
}


# -- HTML output ---------------------------------------------------------------

html_theme = 'pydata_sphinx_theme'
htmlhelp_basename = 'pipnickdoc'
